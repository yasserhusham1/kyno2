-- -----------------------------------------------------------------------------
-- 1. pgcrypto
--    الوظيفة : توليد UUIDs عبر gen_random_uuid()
--              تشفير كلمات المرور عبر crypt() و gen_salt() (bcrypt)
--    يُستخدم في: DEFAULT gen_random_uuid() على كل PK · saas_users.password_hash
-- -----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto
    SCHEMA extensions;


-- -----------------------------------------------------------------------------
-- 2. uuid-ossp
--    الوظيفة : توليد UUIDs عبر uuid_generate_v4() كبديل احتياطي
--              Supabase تفضل gen_random_uuid() لكن هذه تُبقى للتوافق
--    يُستخدم في: فعلياً تحتاطاً — gen_random_uuid() (pgcrypto) هو الأساسي
-- -----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp"
    SCHEMA extensions;


-- -----------------------------------------------------------------------------
-- 3. pg_trgm (Trigram Matching)
--    الوظيفة : تمكين GIN Trigram indexes للبحث النصي السريع
--              يسمح بـ ILIKE '%نص%' على ملايين السجلات بكفاءة عالية
--    يُستخدم في: employees.name · departments.name · job_titles.name
-- -----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pg_trgm
    SCHEMA extensions;


-- -----------------------------------------------------------------------------
-- 4. Schema Comment — توثيق الإصدار
--    الوظيفة : تسجيل إصدار KYNO v2 على مستوى الـ schema
--              يُسهّل التحقق من الإصدار في أدوات DB management
-- -----------------------------------------------------------------------------
COMMENT ON SCHEMA public IS
    'KYNO v2 — SaaS HR Management System | PostgreSQL Schema v2.0.0';


